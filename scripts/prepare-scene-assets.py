"""Download CC BY Earth maps and prepare browser-ready local scene textures.

Run from the project root: python scripts/prepare-scene-assets.py
Optional: --water-archive /path/to/Water_001.zip uses a CC0 normal map.
Without that archive, an original procedural ripple normal is made.
"""
import argparse
import io
import math
from pathlib import Path
import urllib.request
import zipfile
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'day.jpg': '2k_earth_daymap.jpg',
    'night.jpg': '2k_earth_nightmap.jpg',
    'clouds.png': '2k_earth_clouds.jpg',
    'normal.png': '2k_earth_normal_map.tif',
    'specular.png': '2k_earth_specular_map.tif',
}

def earth_maps():
    target = ROOT / 'public/textures/earth'
    target.mkdir(parents=True, exist_ok=True)
    (target / '1k').mkdir(exist_ok=True)
    for name, remote in SOURCES.items():
        path = target / name
        if path.exists():
            image = Image.open(path)
            image.load()
            print('Keeping', path.relative_to(ROOT))
        else:
            url = 'https://www.solarsystemscope.com/textures/download/' + remote
            print('Downloading', url, flush=True)
            request = urllib.request.Request(url, headers={'User-Agent': 'ImportNow-scene-asset-setup/1.0'})
            with urllib.request.urlopen(request, timeout=40) as response:
                original = response.read()
            image = Image.open(io.BytesIO(original))
            image.load()
            if image.width < 1024 or abs(image.width / image.height - 2) > .01:
                raise ValueError('Unexpected Earth map dimensions: ' + remote)
            if name == 'clouds.png':
                mask = image.convert('L')
                image = Image.new('RGBA', mask.size, (255, 255, 255, 0))
                image.putalpha(mask)
            else:
                image = image.convert('RGB')
            if name.endswith('.jpg'):
                path.write_bytes(original)
            else:
                image.save(path, optimize=True)
        small = image.resize((1024, 512), Image.Resampling.LANCZOS)
        small.save(target / '1k' / name, **({'quality': 88, 'optimize': True} if name.endswith('.jpg') else {'optimize': True}))
        print('Prepared', name, image.size, 'and 1024x512 mobile copy', flush=True)

def water_normal(archive):
    path = ROOT / 'public/textures/water/normal.png'
    path.parent.mkdir(parents=True, exist_ok=True)
    if archive:
        with zipfile.ZipFile(archive) as bundle:
            candidates = [n for n in bundle.namelist() if ('normal' in n.lower() or 'norm' in n.lower()) and n.lower().endswith(('.png', '.jpg', '.jpeg'))]
            candidates.sort(key=lambda n: ('dx' in n.lower(), 'gl' not in n.lower(), len(n)))
            if not candidates:
                raise ValueError('Archive contains no normal-map image')
            name = candidates[0]
            image = Image.open(io.BytesIO(bundle.read(name))).convert('RGB')
            if 'dx' in name.lower():
                r, g, b = image.split()
                g = g.point(lambda v: 255 - v)
                image = Image.merge('RGB', (r, g, b))
            image.resize((1024, 1024), Image.Resampling.LANCZOS).save(path, optimize=True)
            origin = 'Water 001 by Katsukagi, CC0; selected ' + name + '; resized/converted to PNG; DX green channel inverted if applicable.'
    else:
        size = 1024
        waves = [(17, 9, .8, .4), (-11, 23, .55, 1.1), (37, 29, .32, 2.4), (63, -41, .18, .9)]
        image = Image.new('RGB', (size, size))
        pixels = image.load()
        for y in range(size):
            for x in range(size):
                dx = dy = 0.
                for kx, ky, weight, phase in waves:
                    slope = math.cos(math.tau * (kx * x + ky * y) / size + phase) * weight * math.tau / size
                    dx += kx * slope
                    dy += ky * slope
                nx, ny, nz = -dx * 3, -dy * 3, 1.
                length = math.sqrt(nx * nx + ny * ny + nz * nz)
                pixels[x, y] = tuple(round((v / length * .5 + .5) * 255) for v in (nx, ny, nz))
        image.save(path, optimize=True)
        origin = 'Original procedural seamless ripple normal generated by scripts/prepare-scene-assets.py.'
    path.with_suffix('.txt').write_text(origin + '\n')
    print('Prepared water:', origin, flush=True)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--water-archive', type=Path)
    args = parser.parse_args()
    earth_maps()
    water_normal(args.water_archive)
    print('Scene textures ready. Earth attribution is in README.md and asset-credits.txt.')
