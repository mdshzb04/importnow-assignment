import assert from 'node:assert/strict';
import { URL } from 'node:url';
import { log } from 'node:console';
import { buildWhatsAppQuote } from '../src/lib/whatsapp.ts';
import { quoteBudgets, quoteCategories } from '../src/data/home.ts';
const fields = { name: '  Asha Rao  ', city: ' Hyderabad ', category: 'Furniture & interiors', quantity: '1 container', budget: '₹1–5 lakh', details: 'Tables & chairs\nhttps://example.test/?a=1&b=2' };
const url = new URL(buildWhatsAppQuote(fields));
assert.equal(url.origin + url.pathname, 'https://wa.me/919989724320');
assert.deepEqual([...url.searchParams.keys()], ['text']);
assert.equal(url.searchParams.get('text'), "Hi ImportNow, I'd like a sourcing quote.\n\nName: Asha Rao\nCity: Hyderabad\nCategory: Furniture & interiors\nQuantity: 1 container\nBudget: ₹1–5 lakh\nDetails: Tables & chairs\nhttps://example.test/?a=1&b=2");
assert.ok(buildWhatsAppQuote(fields).includes('%E2%82%B9'));
assert.ok(buildWhatsAppQuote(fields).includes('%26'));
assert.ok(buildWhatsAppQuote(fields).includes('%0A'));
const optional = new URL(buildWhatsAppQuote({ name: 'Priya', city: '', category: '', quantity: '', budget: '', details: '' }));
assert.equal(optional.searchParams.get('text'), "Hi ImportNow, I'd like a sourcing quote.\n\nName: Priya\nCity: \nCategory: \nQuantity: \nBudget: \nDetails: ");
assert.equal(quoteCategories.length, 8);
assert.equal(quoteBudgets.length, 4);
assert.equal(quoteCategories[0], 'Furniture & interiors');
assert.equal(quoteBudgets[0], 'Under ₹1 lakh');
log('WhatsApp URL checks passed: destination, exact message/field order, trimming, optional fields, Unicode, multiline text, encoding, and select defaults. Nothing sent.');
